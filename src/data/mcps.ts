import type { Mcp, Param, ParamType, Tool } from './types';

/** "query" · "qty:integer" · "?page:integer" (opcional) */
function params(specs: string[]): Param[] {
  return specs.map((spec) => {
    const required = !spec.startsWith('?');
    const [name, type = 'string'] = spec.replace(/^\?/, '').split(':');
    return { name, type: type as ParamType, required };
  });
}

function http(
  name: string,
  method: Tool['method'],
  endpoint: string,
  description: string,
  specs: string[] = [],
  extra: Partial<Tool> = {},
): Tool {
  return { name, kind: 'http', method, endpoint, description, params: params(specs), validated: true, ...extra };
}

function nav(
  name: string,
  steps: string[],
  description: string,
  specs: string[] = [],
  extra: Partial<Tool> = {},
): Tool {
  return { name, kind: 'browser', steps, description, params: params(specs), validated: true, ...extra };
}

/** Serie semanal determinista para las minigráficas de actividad. */
function weekly(base: number, trend: number, seed: number): number[] {
  return Array.from({ length: 12 }, (_, i) => {
    const wobble = Math.sin((i + 1) * (seed % 7 + 1.3)) * 0.18 + Math.cos(i * seed * 0.37) * 0.08;
    return Math.max(0, Math.round(base * (1 + trend * (i / 11)) * (1 + wobble)));
  });
}

